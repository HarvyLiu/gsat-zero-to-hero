/**
 * Self-hosts the site fonts (all SIL OFL 1.1, checked in each package's LICENSE).
 * Copies ONLY the woff2 unicode-range slices from @fontsource into public/fonts/ and writes
 * src/styles/fonts.css without the .woff fallbacks (every browser we target reads woff2),
 * which halves the file count against Cloudflare's 20,000-file limit.
 * Run: node scripts/fonts.mjs   (also part of `npm run assets`)
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const FACES = [
  // [package, css files]  — weights kept to what the design uses
  ['noto-sans-tc', ['400.css', '700.css']],
  ['barlow', ['400.css', '400-italic.css', '500.css', '600.css', '700.css']],
  ['barlow-condensed', ['500.css', '600.css', '700.css', '800.css']],
  ['jetbrains-mono', ['400.css', '700.css']],
];
const out = join(root, 'public', 'fonts');
mkdirSync(out, { recursive: true });
let css = '/* GENERATED by scripts/fonts.mjs from @fontsource (SIL OFL 1.1). Do not edit. */\n';
let files = 0;
for (const [pkg, sheets] of FACES) {
  const dir = join(root, 'node_modules', '@fontsource', pkg);
  for (const sheet of sheets) {
    const src = readFileSync(join(dir, sheet), 'utf8');
    css += src.replace(/src:\s*url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)(?:,\s*url\([^)]+\.woff\)\s*format\('woff'\))?;/g, (_m, file) => {
      const from = join(dir, 'files', file);
      if (!existsSync(from)) throw new Error(`missing ${from}`);
      copyFileSync(from, join(out, file));
      files++;
      return `src: url(/fonts/${file}) format('woff2');`;
    });
  }
}
if (/\.woff'\)|format\('woff'\)/.test(css)) throw new Error('a .woff fallback survived; check the Fontsource CSS shape');
writeFileSync(join(root, 'src', 'styles', 'fonts.css'), css);
console.log(`fonts: ${files} woff2 files → public/fonts, src/styles/fonts.css written`);
