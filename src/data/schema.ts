/**
 * The data contracts for the whole site. Every registry, course file and item bank is validated
 * against these Zod schemas (by its loader and by tests/), so a malformed entry fails the build.
 * Design: docs/design/05-platform.md §1, with the critic's fixes (docs/design/06-critique.md §1, §7):
 *  - curriculum codes are keyed `<domain>:<ASCII code>` (bare codes collide across domains);
 *  - code references are objects {key, part?, case?, role};
 *  - one concept registry, one owner per concept, `deepens` for spiral revisits;
 *  - chapter structure is driven by `kind`; 數A/數B are paths; only extensions and the 116 sprint are tracks;
 *  - facts carry versions[] keyed by date, plus a review-by date.
 */
import { z } from 'astro/zod';

// ---------- primitives ----------
export const LOCALES = ['zh-tw', 'en'] as const;
export type Locale = (typeof LOCALES)[number];

/** A string in both languages; neither may be empty. */
export const L10n = z.object({ 'zh-tw': z.string().min(1), en: z.string().min(1) }).strict();
export type L10n = z.infer<typeof L10n>;

export const ISODate = z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'YYYY-MM-DD');

export const SUBJECT_IDS = ['math', 'physics', 'chemistry', 'biology', 'earth', 'inquiry', 'history', 'geography', 'civics', 'chinese'] as const;
export const SubjectId = z.enum(SUBJECT_IDS);
export type SubjectId = z.infer<typeof SubjectId>;

/**
 * Curriculum domains. Bare 108課綱 codes repeat across domains (國文 Ab-Ⅴ-1 vs 公Ab-Ⅴ-1 vs 地Ab-Ⅴ-1;
 * 國中 自然 codes are shared by all four sciences), so keys are domain-namespaced.
 */
export const DOMAINS = ['math', 'nat', 'soc-elem', 'hist', 'geo', 'civ', 'chi', 'inq', 'exam'] as const;
export const Domain = z.enum(DOMAINS);
export type Domain = z.infer<typeof Domain>;

/** `<domain>:<ASCII code>`, e.g. math:N-10-1, nat:PKa-Vc-3, hist:歷Ba-V-1 is stored as hist:Ba-V-1. */
export const CodeKey = z.string().regex(/^(math|nat|soc-elem|hist|geo|civ|chi|inq|exam):[A-Za-z0-9.\-/]+$/, 'CodeKey must be <domain>:<ASCII code>');
export type CodeKey = z.infer<typeof CodeKey>;

export const MARKS = ['★', '＃', '※'] as const;
export const Mark = z.enum(MARKS);

// ---------- curriculum code registry (generated by scripts/import-codes.mjs) ----------
export const CodeEntry = z
  .object({
    key: CodeKey,
    /** official display form, e.g. 歷Ba-Ⅴ-1 (U+2164) or N-10-1 */
    code: z.string().min(1),
    domain: Domain,
    /** which subject's syllabus lists it (a 國中 自然 code may serve several) */
    subjects: z.array(SubjectId).min(1),
    /** 國小3…國中9, 10, 11A, 11B, 12甲, 12乙, 必修, 選修 */
    level: z.string().min(1),
    /** yes = 學測 scope; partial = ★/＃ handling; no = beyond 學測 (分科/選修); background = 國小/國中 bridge */
    inGsat: z.enum(['yes', 'partial', 'no', 'background', 'unknown']),
    gsatTrack: z.enum(['both', 'A', 'B', 'none']).default('both'),
    marks: z.array(Mark).default([]),
    title: z.object({ 'zh-tw': z.string().min(1), en: z.string().optional() }),
    keyConcepts: z.array(z.string()).default([]),
    dependsOn: z.array(CodeKey).default([]),
    /** research verification status */
    status: z.enum(['verified', 'corrected', 'added', 'unverified']),
    source: z.string().min(1),
  })
  .strict();
export type CodeEntry = z.infer<typeof CodeEntry>;

/** How a chapter relates to a code. */
export const CodeRef = z
  .object({
    key: CodeKey,
    /** a named portion of the code (e.g. "√2 proof ★", "三垂線定理") */
    part: z.string().optional(),
    /** either/or case for 地理 Cc/Ch ("southeast-asia" | "south-asia", "latin-america" | "ssa") */
    case: z.string().optional(),
    role: z.enum(['teaches', 'reviews', 'bridges', 'toolkit', 'beyond', 'uses']).default('teaches'),
  })
  .strict();
export type CodeRef = z.infer<typeof CodeRef>;

// ---------- course structure ----------
