/** A chapter id is global: '<subject>/<slug>' (or 'site/<slug>' for site-level chapters). */
export const ChapterId = z.string().regex(/^(site|math|physics|chemistry|biology|earth|inquiry|history|geography|civics|chinese)\/[a-z0-9-]+$/);
export type ChapterId = z.infer<typeof ChapterId>;

/** A concept / glossary id: '<subject or site>.<kebab>' */
export const TermId = z.string().regex(/^(site|math|physics|chemistry|biology|earth|inquiry|history|geography|civics|chinese)\.[a-z0-9-]+$/);
export type TermId = z.infer<typeof TermId>;

export const ChapterDef = z
  .object({
    slug: z.string().regex(/^[a-z0-9-]+$/),
    title: L10n,
    blurb: L10n,
    objectives: z.array(L10n).min(1).max(5),
    kind: Kind,
    /** subject paths this chapter is on (omitted = every path of the subject), e.g. ['mathA'] */
    paths: z.array(z.string()).optional(),
    codes: z.array(CodeRef).default([]),
    marks: z.array(Mark).default([]),
    newConcepts: z.array(TermId).default([]),
    uses: z.array(TermId).default([]),
    /** for sprint review chapters: concepts reviewed (must exist in the term registry) */
    reviews: z.array(TermId).default([]),
    prereqs: z.array(ChapterId).default([]),
    /** for tracks with a stated entry level (the 116 sprint): codes assumed already studied */
    assumes: z.array(CodeKey).default([]),
    minutes: z.number().int().positive(),
    sources: z.array(z.string()).min(1),
    examItems: z.array(z.string()).default([]),
    misconceptions: z.array(z.string()).default([]),
    /** internal note on what the chapter does (docs only) */
    activity: z.string().default(''),
  })
  .strict();
export type ChapterDef = z.infer<typeof ChapterDef>;

export const TrackDef = z
  .object({
    id: z.string().regex(/^[a-z0-9-]+$/),
    title: L10n,
    entry: z.object({ after: z.array(ChapterId), note: L10n }),
  })
  .strict();

export const PartDef = z
  .object({
    num: z.number().int().nonnegative(),
    id: z.string().regex(/^[a-z0-9-]+$/),
    title: L10n,
    question: L10n,
    /** internal rationale for where the part sits (docs only, not translated) */
    whyHere: z.string().min(1),
    track: z.union([z.literal('core'), TrackDef]).default('core'),
    chapters: z.array(ChapterDef).min(1),
  })
  .strict();
export type PartDef = z.infer<typeof PartDef>;

export const CourseFile = z
  .object({
    $comment: z.string().optional(),
    subject: z.union([SubjectId, z.literal('site')]),
    version: z.number().int(),
    date: ISODate,
    decisions: z.array(z.string()).default([]),
    openQuestions: z.array(z.string()).default([]),
    parts: z.array(PartDef).min(1),
  })
  .strict();
export type CourseFile = z.infer<typeof CourseFile>;

// ---------- subjects ----------
export const SubjectDef = z
  .object({
    id: SubjectId,
    title: L10n,
    short: L10n,
    papers: z.array(z.enum(['mathA', 'mathB', 'science', 'social', 'chinese'])).min(1),
    status: z.enum(['pilot', 'active', 'beta', 'planned']),
    paths: z.array(z.object({ id: z.string(), label: L10n })).min(1),
    /** bibliography id of the 樂詞網 高中以下 term set, where one exists */
    termSource: z.string().optional(),
  })
  .strict();
export type SubjectDef = z.infer<typeof SubjectDef>;

// ---------- glossary / concept registry ----------
export const TermEntry = z
  .object({
    id: TermId,
    zh: z.string().min(1),
    en: z.string().min(1),
    zhuyin: z.string().optional(),
    def: L10n,
    /** where the zh/en term pair comes from (樂詞網 where a 高中以下 set exists) */
    source: z.object({ id: z.string().min(1), locator: z.string().optional(), verbatim: z.boolean().optional() }),
    /** 'vocab' terms are glossary-only and exempt from the no-jump rule */
    kind: z.enum(['concept', 'vocab']).default('concept'),
    /** spiral revisit of an earlier concept (e.g. 國中 vs 高中 Newton's laws) */
    deepens: TermId.optional(),
    aliases: z.object({ zh: z.array(z.string()).optional(), en: z.array(z.string()).optional() }).optional(),
    /** wording we must not use (e.g. Mainland-only terms) */
    forbidden: z.array(z.string()).optional(),
  })
  .strict();
export type TermEntry = z.infer<typeof TermEntry>;

// ---------- bibliography & licences ----------
export const LicenceDef = z
  .object({
    id: z.string().regex(/^[a-z0-9.-]+$/),
    name: z.string().min(1),
    url: z.string().url().optional(),
    mayQuote: z.enum(['verbatim-only', 'short', 'yes', 'no', 'link-only']),
    mayModify: z.boolean(),
    mayRehost: z.boolean(),
    attributionRequired: z.boolean(),
    nonCommercialOnly: z.boolean(),
    note: z.string().optional(),
  })
  .strict();
export type LicenceDef = z.infer<typeof LicenceDef>;

export const SourceDef = z
  .object({
    id: z.string().regex(/^[a-z0-9.-]+$/),
    title: z.string().min(1),
    url: z.string().regex(/^https:\/\//, 'sources must be https'),
    publisher: z.string().min(1),
    kind: z.enum(['curriculum', 'exam-official', 'law', 'term-db', 'dictionary', 'dataset', 'software', 'paper', 'web', 'news']),
    licence: z.string().min(1),
    accessed: ISODate,
    /** document version / date when the source has one, e.g. '初版 115/8/4' */
    version: z.string().optional(),
    attribution: L10n.optional(),
  })
  .strict();
export type SourceDef = z.infer<typeof SourceDef>;

// ---------- time-sensitive facts ----------
const FactValue = z.union([L10n, z.object({ n: z.number(), unit: L10n }).strict()]);
export const FactDef = z
  .object({
    id: z.string().regex(/^[a-z0-9.-]+$/),
    subject: z.union([SubjectId, z.literal('site')]),
    label: L10n,
    versions: z.array(z.object({ value: FactValue, validFrom: ISODate, validTo: ISODate.optional(), basis: z.string().optional() }).strict()).min(1),
    asOf: ISODate,
    reviewBy: ISODate,
    sources: z.array(z.string()).min(1),
    note: L10n.optional(),
  })
  .strict();
export type FactDef = z.infer<typeof FactDef>;

// ---------- misconceptions (only documented ones render) ----------
export const MisconceptionDef = z
  .object({
    id: z.string().regex(/^[a-z]+\.[a-z0-9-]+$/),
    codes: z.array(CodeKey).default([]),
    wrong: L10n,
    right: L10n,
    contrast: L10n.optional(),
    sources: z.array(z.string()).min(1),
    /** verified = documented and checked; pending = source not yet re-opened; low-p = low success rate only, not a coded error */
    status: z.enum(['verified', 'pending', 'low-p']),
  })
  .strict();
export type MisconceptionDef = z.infer<typeof MisconceptionDef>;

// ---------- exam registries ----------
export const SittingDef = z
  .object({
    id: z.string(),
    label: L10n,
    sessions: z.array(z.object({ paper: z.string(), label: L10n, start: z.string().regex(/\+08:00$/), end: z.string().regex(/\+08:00$/) }).strict()).min(1),
    milestones: z.array(z.object({ id: z.string(), label: L10n, date: ISODate }).strict()).default([]),
    sources: z.array(z.string()).min(1),
    reviewBy: ISODate,
  })
  .strict();

/** Official CEEC items are indexed by link only; their text is never stored. */
export const ExamItemRef = z
  .object({
    id: z.string().regex(/^\d{3}-[a-zA-Z]+-q[\d-]+$/),
    sitting: z.number().int(),
    paper: z.enum(['mathA', 'mathB', 'science', 'social', 'chinese-comp', 'chinese-writing']),
    numbers: z.array(z.number().int().positive()).min(1),
    type: z.enum(['single', 'multi', 'fill', 'mixed', 'nonchoice', 'group']),
    codes: z.array(CodeKey).default([]),
    paperUrl: z.string().regex(/^https:\/\/www\.ceec\.edu\.tw\//),
    answerUrl: z.string().regex(/^https:\/\/www\.ceec\.edu\.tw\//).optional(),
    rubricUrl: z.string().regex(/^https:\/\/www\.ceec\.edu\.tw\//).optional(),
    note: L10n.optional(),
    curriculum: z.enum(['108', 'legacy']),
    verified: z.boolean(),
  })
  .strict();
export type ExamItemRef = z.infer<typeof ExamItemRef>;

// ---------- practice items (YAML, single source for the site and the Python harness) ----------
const ItemText = z.object({ stem: z.string().min(1), options: z.array(z.string()).optional(), explain: z.string().min(1), hint: z.string().optional() }).strict();
const ItemBase = {
  id: z.string().regex(/^[a-z0-9-]+(@\d+)?$/),
  codes: z.array(CodeKey).default([]),
  /** practice items are always our own; official items are linked, never copied */
  origin: z.literal('original'),
  /** optional: an official item this one is modelled on (link only) */
  modelledOn: z.string().optional(),
  skills: z.array(z.string()).default([]),
  review: z.boolean().default(true),
  text: z.object({ 'zh-tw': ItemText, en: ItemText }).strict(),
  /** machine verification: a harness check id (harness/checks/…) that recomputes the answer */
  verify: z.string().optional(),
};
export const Item = z.discriminatedUnion('type', [
  z.object({ ...ItemBase, type: z.literal('single'), answer: z.number().int().nonnegative() }).strict(),
  z.object({ ...ItemBase, type: z.literal('multi'), answer: z.array(z.number().int().nonnegative()).min(1) }).strict(),
  /** 選填: one string per bubble cell, alphabet 0–9 and '−' (U+2212) */
  z.object({ ...ItemBase, type: z.literal('fill'), answer: z.array(z.string().regex(/^[0-9−]$/)).min(1) }).strict(),
  z.object({ ...ItemBase, type: z.literal('numeric'), accept: z.enum(['int', 'decimal', 'fraction']), answer: z.union([z.number(), z.string()]) }).strict(),
  z
    .object({
      ...ItemBase,
      type: z.literal('mixed'),
      rubric: z.object({ criteria: z.array(z.object({ id: z.string(), points: z.number().positive(), text: L10n }).strict()).min(1) }).strict(),
      model: L10n,
    })
    .strict(),
]);
export type Item = z.infer<typeof Item>;

export const ItemBank = z
  .object({
    chapter: ChapterId,
    items: z.array(Item).min(1),
  })
  .strict();
export type ItemBank = z.infer<typeof ItemBank>;
